#!/usr/bin/env node
/**
 * Write the list of files that actually exist under `public/assets`.
 *
 * Course art is looked up by slug, and most races have no photograph yet.
 * Without this, every one of them asks the network — and because the media
 * component falls back across extensions, each miss costs five requests. The
 * race directory alone fired eighty-five 404s to render a page of gradients.
 *
 * A static export knows its own files at build time, so it need not guess.
 * `prebuild` regenerates this, which keeps it honest: add a photo, build, and
 * it appears with no code change.
 */

import { readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS = join(ROOT, "public", "assets");
const OUT = join(ROOT, "lib", "assetManifest.ts");

async function walk(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await walk(full)));
    else found.push(full);
  }
  return found;
}

const files = (await walk(ASSETS).catch(() => []))
  .map((f) => relative(join(ROOT, "public"), f).split("\\").join("/"))
  .sort();

await writeFile(
  OUT,
  `/* Generated by scripts/asset-manifest.mjs — do not edit.
   Regenerated on every build (see the \`prebuild\` script), so it cannot
   drift from what is on disk. */

export const ASSET_FILES: ReadonlySet<string> = new Set([
${files.map((f) => `  ${JSON.stringify(f)},`).join("\n")}
]);

/** Whether a file is actually present, so nothing asks the network blindly. */
export function assetExists(path: string | null | undefined): boolean {
  return !!path && ASSET_FILES.has(path.replace(/^\\/+/, ""));
}
`,
);
console.log(`asset manifest: ${files.length} files`);
